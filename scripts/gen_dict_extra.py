PERSIAN = set("آائءبپتثجچحخدذرزژسشصضطظعغفقکگلمنوهی")

def existing_words():
    src = io.open(SRC_DICT, encoding="utf-8").read()
    m = re.search(r"export const DICT_WORDS: string\[\] = \[(.*?)\];", src, re.S)
    words = re.findall(r'"([^"]+)"', m.group(1))
    return words

def clean(word):
    w = word.strip()
    return w if w and not w.endswith("?") else ""

def valid(w):
    if not w: return False
    if " " in w or "\u200c" in w: return False   # no spaces / no ZWNJ
    if len(w) < 2 or len(w) > 12: return False
    return all(ch in PERSIAN for ch in w)

def main():
    existing = existing_words()
    ex = set(existing)
    added, skipped_dup, skipped_bad = [], set(), []
    for cat, blob in CATEGORIES.items():
        for raw in blob.split():
            w = clean(raw)
            if not w: continue
            if not valid(w):
                skipped_bad.append((cat, w)); continue
            if w in ex:
                skipped_dup.add(w); continue
            ex.add(w); added.append((cat, w))
    # sort alphabetically for a tidy diff-friendly file
    added.sort(key=lambda t: t[1])
    total_new = len(added)
    total_all = len(existing) + total_new
    lines = []
    lines.append("/* ------------------------------------------------------------------")
    lines.append(" *  واژه‌سفر — data/dictionary_extra.ts  (AUTO-GENERATED by scripts/gen_dict_extra.py)")
    lines.append(" *  v4 — +%d new common Persian words (user: «دایره لغات بازی دورهمی" % total_new)
    lines.append(" *  افزایش بده ۱۰۰۰ تا لغت بزار»). Merged into the runtime validity set")
    lines.append(" *  (levelsIndex.ts → FULL_DICT) so دورهمی and bonus-word checking")
    lines.append(" *  recognize a much bigger real-Persian vocabulary (%d words total)." % total_all)
    lines.append(" *  Categories: %s" % " · ".join(CATEGORIES.keys()))
    lines.append(" * ------------------------------------------------------------------ */")
    lines.append("export const EXTRA_WORDS: string[] = [")
    chunk, per_line = [], 12
    for _, w in added:
        chunk.append('"%s"' % w)
        if len(chunk) == per_line:
            lines.append("  " + ", ".join(chunk) + ",")
            chunk = []
    if chunk:
        lines.append("  " + ", ".join(chunk) + ",")
    lines.append("];")
    lines.append("")
    lines.append("export const EXTRA_WORDS_COUNT = %d;" % total_new)
    lines.append("")
    io.open(OUT, "w", encoding="utf-8").write("\n".join(lines))
    print("existing: %d" % len(existing))
    print("new words added: %d" % total_new)
    print("TOTAL dictionary size: %d" % total_all)
    print("skipped as duplicates of existing: %d" % len(skipped_dup))
    if skipped_bad:
        print("skipped invalid (space/ZWNJ/latin/short): %d -> %s" % (len(skipped_bad), [b[1] for b in skipped_bad][:30]))

if __name__ == "__main__":
    main()
