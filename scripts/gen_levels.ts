/* ---- difficulty ramp (progressive: ch1 easy → ch10 hard) ---- */
function wheelLenFor(i: number): number {
  const ch = Math.floor(i / 10) + 1;             // 1..10
  const pos = i % 10;                             // 0..9 within chapter
  const base = [4, 4, 5, 5, 5, 6, 6, 6, 7, 7][ch - 1];
  // +1 wheel letter in the last third of a chapter (capped at 7)
  return pos >= 7 && base < 7 ? base + 1 : base;
}
function wantWordsFor(i: number): number {
  const ch = Math.floor(i / 10) + 1;
  const pos = i % 10;
  const base = [4, 4, 4, 5, 5, 6, 6, 6, 7, 7][ch - 1];
  // gentle in-chapter ramp: +1 word on the last third
  return pos >= 7 ? base + 1 : base;
}
/** min main-word length per chapter (2-letter fillers only in ch1-3, max 1) */
function minLenFor(ch: number): number {
  return ch <= 3 ? 2 : 3;
}

