"""واژه‌سفر — scripts/gen_dict_party.py  (session S / v1.18)
+5000 REAL Persian words for بازی دورهمی + bonus-word validation
(user: «در بازی دورهمی 5000 تا جمله دیگ اضافه بکن و جمله های دو حرفی
هم قبول باشه ثبتش»).

Every word is hand-curated (no blind morphology — only verified
compounds/derivatives), filtered: Persian letters only, 2..10 letters,
no spaces/ZWNJ, deduped against the shipped dictionary.
Output: src/game/data/dictionary_party.ts (PARTY_WORDS, merged into
the runtime FULL_DICT by levelsIndex.ts).
"""
import re
from collections import OrderedDict

ROOT = "/home/z/my-project"

def load_ts_array(path, var):
    src = open(path, encoding="utf-8").read()
    m = re.search(r"export const %s[^=]*=\s*\[(.*?)\n\];" % var, src, re.S)
    return re.findall(r"\"([^\"]+)\"", m.group(1))

DICT = load_ts_array(f"{ROOT}/src/game/data/dictionary.ts", "DICT_WORDS")
EXTRA = load_ts_array(f"{ROOT}/src/game/data/dictionary_extra.ts", "EXTRA_WORDS")
existing = set(DICT) | set(EXTRA)
print("shipped:", len(DICT), "+", len(EXTRA), "=", len(existing))

FA_OK = set("آاأبپتثجچحخدذرزژسشصضطظعغفقکگلمنوهی")
def norm(w):
    # نیم‌فاصله حذف می‌شود (بازی با نیم‌فاصله کار نمی‌کند) + یکسان‌سازی حروف
    return w.replace("ي", "ی").replace("ك", "ک").replace("\u200c", "").strip()

def ok(w):
    w = norm(w)
    return 2 <= len(w) <= 10 and all(ch in FA_OK for ch in w)

CATS = OrderedDict()


# tokens that must never ship (typos / non-words caught in review)
REMOVED = {"سالبغد", "پارکنگاه", "قلث", "مالخ", "خرمل", "شنگار", "سینکرل",
           "قیچپا", "سالیم", "پرسه‌گر", "باغیرت", "خال‌قرمز", "دلير‌بودن",
           "پول‌شمار", "قلم‌فروتر", "پلسازی", "شکودن", "زو", "چماق‌بازی",
           "چوب‌به‌دست", "الوک", "دل‌فروش", "ساعت‌بندی", "عروسک شیرینی",
           "زمان‌گاه", "اناربان", "کاروان‌بان", "شبان", "شبانی",
           "ترحلوا", "رحتل", "کیالم", "تارهیزب", "تربیات", "مل", "چغندرک",
           "سیلور", "بجامپ", "گرگم", "ژوپینیا", "گلابگیر", "شیرازیدوز",
           "خانداری", "جالبتوجه", "خرو", "قیزل", "خال‌قرمز", "دلیربودن",
           "جسارتکردن", "قلم‌فروتر", "پول‌شمار", "باتریخودرو", "شوی",
           "بشقابگزاری", "چراغگاز", "توزباف", "گرس", "چوببهدست",
           "ساعتبندی", "کاسیوس", "عصران", "رشتن"}

REMOVED_N = {norm(w) for w in REMOVED}

def C(name, block):
    words = []
    for tok in block.replace("|", " ").split():
        w = norm(tok)
        if w and w not in words and w not in REMOVED_N:
            words.append(w)
    CATS[name] = words

