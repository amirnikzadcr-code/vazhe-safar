# ================= DERIVATIONS (verified families) =====================
# Solid-written inflections (جمع با «ها»، تفضیلی «تر/ترین»، صفت مصدری)
# — the same convention used by mainstream Iranian word-game dictionaries.

ALL_POOL = []
for _n, _ws in CATS.items():
    ALL_POOL.extend(_ws)
ALL_POOL.extend(norm(w) for w in existing)
ALL_POOL = [w for w in dict.fromkeys(ALL_POOL) if ok(w)]

SKIP_END = tuple("هیاؤءو")   # solid inflection of these endings looks wrong

# واژه‌های نقش‌نما (حروف/اعداد) — جمع گرفتنشان بی‌معناست
FUNCTION_WORDS = set("""چند هیچ هرگز اغلب همیشه گاهی همه بعضی کم زیاد چقدر هرکس
اول دوم سوم چهارم پنجم ششم هفتم هشتم نهم دهم آخر یک دو سه چهار پنج شش هفت هشت نه ده
بیست سی چهل پنجاه شصت هفتاد هشتاد نود صد هزار میلیون میلیارد نخست حالا الان بهزودی""".split())

def plural_ha(stems):
    out = []
    for s in stems:
        if len(s) < 3 or len(s) > 7 or s.endswith(SKIP_END) or s.endswith("ن") or s.endswith("ها"):
            continue
        if s in FUNCTION_WORDS:
            continue
        p = s + "ها"
        if ok(p):
            out.append(p)
    return out

def comparatives(adjs):
    out = []
    for a in adjs:
        if len(a) < 3 or len(a) > 7 or a.endswith(SKIP_END) or a.endswith("ن"):
            continue
        for suf in ("تر", "ترین"):
            w = a + suf
            if ok(w):
                out.append(w)
    return out

REL_OK = {"چند", "دیگر", "بعد"}   # چندی/دیگری/بعدی واژه‌های واقعی‌اند

def rel_adjs(stems):
    """نسبت/نکره: کوه → کوهی، کتاب → کتابی (real Persian forms)"""
    out = []
    for s in stems:
        if len(s) < 3 or len(s) > 7 or s.endswith(SKIP_END) or s.endswith("ن") or s.endswith("ی"):
            continue
        if s in FUNCTION_WORDS and s not in REL_OK:
            continue
        w = s + "ی"
        if ok(w):
            out.append(w)
    return out

def verb_adjs(infs):
    out = []
    for v in infs:
        if len(v) < 4 or len(v) > 7 or not v.endswith("ن"):
            continue
        stem = v[:-1]
        if len(stem) < 3:
            continue
        w = stem + "نی"         # رفتن → رفتنی
        if ok(w):
            out.append(w)
    return out

ADJ_CATS = {"صفت‌ها", "صفت‌های بیشتر", "رنگ‌ها", "وابسته‌های نسبی"}
VERB_CATS = {"فعل‌ها", "فعل‌های بیشتر"}

ADJ_STEMS = [w for n, ws in CATS.items() if n in ADJ_CATS for w in ws]
INF_STEMS = [w for n, ws in CATS.items() if n in VERB_CATS for w in ws]

plural_words = plural_ha(ALL_POOL)
comp_words = comparatives(ADJ_STEMS)
vadj_words = verb_adjs(INF_STEMS)
rel_words = rel_adjs(ALL_POOL)   # نسبت از کل گنجینه (کوهی، کتابی، دریایی...)
print("derivations: plural", len(plural_words), "| comparative", len(comp_words), "| verb-adj", len(vadj_words), "| rel-adj", len(rel_words))

CATS["جمع‌ها"] = plural_words
CATS["صفت‌های برتر"] = comp_words
CATS["صفت‌های مصدری"] = vadj_words
CATS["صفت‌های نسبت"] = rel_words

# ================= EMIT =================
seen_cat = {}
new_all = []
dupe_ship = dupe_int = bad = 0
for name, ws in CATS.items():
    for raw in ws:
        w = norm(raw)
        if not ok(w):
            bad += 1
            continue
        if w in existing:
            dupe_ship += 1
            continue
        if w in seen_cat:
            dupe_int += 1
            continue
        seen_cat[w] = name
        new_all.append((w, name))

print(f"raw tokens: {sum(len(v) for v in CATS.values())}")
print(f"NEW unique valid: {len(new_all)} | dupes vs shipped: {dupe_ship} | internal: {dupe_int} | filtered: {bad}")

